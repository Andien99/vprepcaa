-- Migration 0001: identity
-- Brings Better Auth's tables (created in 0000_auth.sql) into the platform schema.
--
--   user    -> users          (+ year_level, status)
--   account -> auth_accounts  (plaintext OAuth tokens cleared; format guards added)
--   session -> sessions
--
-- Better Auth still addresses these as its "user", "account" and "session" models:
-- worker/src/db/schema.js exports them under those names, pointing at the new tables.
-- ALTER TABLE ... RENAME also rewrites the foreign keys in account/session.
--
-- Conventions for every table in this schema (matching 0000_auth.sql):
--   * id          TEXT primary key, generated by the app (crypto.randomUUID()) or Better Auth.
--   * timestamps  INTEGER milliseconds since the Unix epoch, default (unixepoch() * 1000).
--   * updated_at  refreshed by an AFTER UPDATE trigger unless the statement sets it.
--   * booleans    INTEGER 0/1 with a CHECK.
-- D1 enforces foreign keys on every query (PRAGMA foreign_keys = on).
--
-- DEPLOY NOTE: the Worker must be deployed straight after this migration is applied
-- (the old code queries the old table names).

-- ---------------------------------------------------------------------------
-- users (was: user)
-- ---------------------------------------------------------------------------
ALTER TABLE `user` RENAME TO `users`;

DROP INDEX IF EXISTS `user_email_unique`;
CREATE UNIQUE INDEX `ux_users_email` ON `users` (`email`);
CREATE INDEX `ix_users_platform_role` ON `users` (`platform_role`);

ALTER TABLE `users` ADD COLUMN `year_level` integer
    CHECK (`year_level` IS NULL OR `year_level` BETWEEN 7 AND 12);
ALTER TABLE `users` ADD COLUMN `status` text DEFAULT 'active' NOT NULL
    CHECK (`status` IN ('active', 'suspended'));

-- platform_role was created without a CHECK; SQLite can't add one to an existing
-- column without rebuilding the table, so triggers enforce it.
CREATE TRIGGER `trg_users_platform_role_ins` BEFORE INSERT ON `users`
FOR EACH ROW WHEN NEW.`platform_role` NOT IN ('student', 'teacher', 'admin')
BEGIN
    SELECT RAISE(ABORT, 'users.platform_role must be student, teacher or admin');
END;

CREATE TRIGGER `trg_users_platform_role_upd` BEFORE UPDATE OF `platform_role` ON `users`
FOR EACH ROW WHEN NEW.`platform_role` NOT IN ('student', 'teacher', 'admin')
BEGIN
    SELECT RAISE(ABORT, 'users.platform_role must be student, teacher or admin');
END;

CREATE TRIGGER `trg_users_updated_at` AFTER UPDATE ON `users`
FOR EACH ROW WHEN NEW.`updated_at` = OLD.`updated_at`
BEGIN
    UPDATE `users` SET `updated_at` = (unixepoch() * 1000) WHERE `id` = NEW.`id`;
END;

-- ---------------------------------------------------------------------------
-- auth_accounts (was: account)
-- Better Auth now encrypts OAuth tokens (account.encryptOAuthTokens in
-- worker/src/auth/index.js). Tokens written before that were plaintext, so they
-- are cleared here; sign-in doesn't need them and Google issues new ones next login.
-- The triggers reject any token that isn't Better Auth ciphertext (hex, or the
-- versioned "$ba$" format) and any password that isn't a Better Auth scrypt hash
-- ("<hex salt>:<hex key>").
-- ---------------------------------------------------------------------------
ALTER TABLE `account` RENAME TO `auth_accounts`;

UPDATE `auth_accounts` SET `access_token` = NULL, `refresh_token` = NULL, `id_token` = NULL;

CREATE UNIQUE INDEX `ux_auth_accounts_provider` ON `auth_accounts` (`provider_id`, `account_id`);
CREATE INDEX `ix_auth_accounts_user` ON `auth_accounts` (`user_id`);

CREATE TRIGGER `trg_auth_accounts_no_plaintext_ins` BEFORE INSERT ON `auth_accounts`
FOR EACH ROW WHEN
       (NEW.`access_token`  IS NOT NULL AND NEW.`access_token`  NOT GLOB '$ba$*' AND NEW.`access_token`  GLOB '*[^0-9a-fA-F]*')
    OR (NEW.`refresh_token` IS NOT NULL AND NEW.`refresh_token` NOT GLOB '$ba$*' AND NEW.`refresh_token` GLOB '*[^0-9a-fA-F]*')
    OR (NEW.`id_token`      IS NOT NULL AND NEW.`id_token`      NOT GLOB '$ba$*' AND NEW.`id_token`      GLOB '*[^0-9a-fA-F]*')
    OR (NEW.`password`      IS NOT NULL AND (NEW.`password` NOT GLOB '?*:?*' OR NEW.`password` GLOB '*[^0-9a-fA-F:]*'))
BEGIN
    SELECT RAISE(ABORT, 'auth_accounts: tokens must be encrypted and passwords hashed');
END;

CREATE TRIGGER `trg_auth_accounts_no_plaintext_upd`
BEFORE UPDATE OF `access_token`, `refresh_token`, `id_token`, `password` ON `auth_accounts`
FOR EACH ROW WHEN
       (NEW.`access_token`  IS NOT NULL AND NEW.`access_token`  NOT GLOB '$ba$*' AND NEW.`access_token`  GLOB '*[^0-9a-fA-F]*')
    OR (NEW.`refresh_token` IS NOT NULL AND NEW.`refresh_token` NOT GLOB '$ba$*' AND NEW.`refresh_token` GLOB '*[^0-9a-fA-F]*')
    OR (NEW.`id_token`      IS NOT NULL AND NEW.`id_token`      NOT GLOB '$ba$*' AND NEW.`id_token`      GLOB '*[^0-9a-fA-F]*')
    OR (NEW.`password`      IS NOT NULL AND (NEW.`password` NOT GLOB '?*:?*' OR NEW.`password` GLOB '*[^0-9a-fA-F:]*'))
BEGIN
    SELECT RAISE(ABORT, 'auth_accounts: tokens must be encrypted and passwords hashed');
END;

CREATE TRIGGER `trg_auth_accounts_updated_at` AFTER UPDATE ON `auth_accounts`
FOR EACH ROW WHEN NEW.`updated_at` = OLD.`updated_at`
BEGIN
    UPDATE `auth_accounts` SET `updated_at` = (unixepoch() * 1000) WHERE `id` = NEW.`id`;
END;

-- ---------------------------------------------------------------------------
-- sessions (was: session)
-- Better Auth looks sessions up by token, so the token is stored as issued. The
-- browser cookie is HMAC-signed with BETTER_AUTH_SECRET (a Worker secret, not in
-- D1), so a copy of this table can't be turned into a working cookie.
-- ---------------------------------------------------------------------------
ALTER TABLE `session` RENAME TO `sessions`;

DROP INDEX IF EXISTS `session_token_unique`;
CREATE UNIQUE INDEX `ux_sessions_token` ON `sessions` (`token`);
CREATE INDEX `ix_sessions_user` ON `sessions` (`user_id`);
CREATE INDEX `ix_sessions_expires` ON `sessions` (`expires_at`);
